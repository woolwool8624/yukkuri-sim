export function voicesOf(characterId: string): VoiceDef[] {
  return VOICES[characterId] ?? [];
}

const STORAGE_KEY = 'voice';

/** 今のキャラクターの口調を覚えておき、場面のキーからセリフを選ぶ */
export class Voice {
  /** キャラクター id → 選んでいる口調の id（保存する） */
  private readonly chosen: Record<string, string> = { ...loadJSON<Record<string, string>>(STORAGE_KEY) };

  constructor(private readonly characterId: () => string) {}

  /** 今のキャラクターで選んでいる口調の id（口調がなければ ''） */
  get id(): string {
    const list = voicesOf(this.characterId());
    const id = this.chosen[this.characterId()];
    return list.some((v) => v.id === id) ? id : (list[0]?.id ?? '');
  }

  set id(id: string) {
    this.chosen[this.characterId()] = id;
    saveJSON(STORAGE_KEY, this.chosen);
  }

  /** 場面 key のセリフの一覧（今の口調に書いてあればそれ、なければ共通） */
  list(key: LineKey): string[] {
    const v = voicesOf(this.characterId()).find((x) => x.id === this.id);
    return v?.lines[key] ?? COMMON[key];
  }

  /** 場面 key のセリフを 1 つ選ぶ */
  line(key: LineKey): string {
    return pick(this.list(key));
  }
}
